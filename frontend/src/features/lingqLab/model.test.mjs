import assert from 'node:assert/strict'
import { readState, isLearning, newWordPercent, scheduleReview, STORAGE_KEY } from './model.js'
const fakeStorage = data => ({ getItem: key => { assert.equal(key, STORAGE_KEY); return data } })
const legacy = { vocabulary: { model: { status: 'learning', meaning: '模型', context: 'Original lesson' }, known: { status: 'known' }, broken: null }, imports: [{ id: 'mine', title: 'My lesson', text: 'A model.' }], completed: ['ai'], reviewCount: 7 }
const migrated = readState(fakeStorage(JSON.stringify(legacy)))
assert.equal(migrated.vocabulary.model.status, '1')
assert.equal(migrated.vocabulary.model.meaning, '模型')
assert.equal(migrated.vocabulary.model.dueAt, 0)
assert.equal(migrated.vocabulary.known.status, 'known')
assert.equal(migrated.vocabulary.broken, undefined)
assert.equal(migrated.imports[0].id, 'mine')
assert.deepEqual(migrated.completed, ['ai'])
assert.equal(migrated.reviewCount, 7)
assert.deepEqual(readState(fakeStorage('{broken')).vocabulary, {})
assert.equal(isLearning({status:'ignored'}), false)
assert.equal(isLearning({status:'known'}), false)
assert.equal(isLearning({status:'4'}), true)
assert.equal(newWordPercent('Model model data unknown.', { model: {status:'ignored'}, data: {status:'known'} }), 33)
const now = 1000000
assert.equal(scheduleReview({status:'1'}, true, now).dueAt, now + 2*86400000)
assert.equal(scheduleReview({status:'2'}, true, now).status, '3')
assert.equal(scheduleReview({status:'4'}, true, now).status, 'known')
assert.equal(scheduleReview({status:'3'}, false, now).dueAt, now + 600000)
assert.equal(scheduleReview({status:'3'}, false, now).status, '2')
const settings = readState(fakeStorage(JSON.stringify({reader:{size:29,theme:'night',font:'sans'},sidebarCollapsed:true})))
assert.deepEqual(settings.reader, {size:29,theme:'night',font:'sans'})
assert.equal(settings.sidebarCollapsed, true)
console.log('PASS: legacy migration, malformed storage, persistence fields, ignored/new-word ratio, review scheduling, reading preferences')
const { sanitizePlaylists, collectionStats, movePlaylistLesson } = await import('./model.js')
assert.deepEqual(sanitizePlaylists(undefined), [])
assert.deepEqual(sanitizePlaylists([null,{id:'one',title:' My list ',lessonIds:['ai','ai','design',3]}]), [{id:'one',title:'My list',lessonIds:['ai','design']}])
assert.deepEqual(movePlaylistLesson(['a','b','c'],1,-1), ['b','a','c'])
assert.deepEqual(movePlaylistLesson(['a','b','c'],0,-1), ['a','b','c'])
assert.deepEqual(movePlaylistLesson(['a','b','c'],1,1), ['a','c','b'])
const stats = collectionStats([{id:'a',text:'Model model data ignored new.'}],{model:{status:'known'},data:{status:'2'},ignored:{status:'ignored'}},['a'])
assert.deepEqual(stats,{total:5,unique:4,completed:1,lessonCount:1,new:1,learning:1,known:1,ignored:1})
const restored = readState(fakeStorage(JSON.stringify({...legacy,playlists:[{id:'p',title:'Test',lessonIds:['ai','mine']}]})))
assert.equal(restored.playlists[0].lessonIds[1], 'mine')
assert.equal(restored.imports[0].id, 'mine')
assert.equal(restored.vocabulary.model.meaning, '模型')
assert.equal(restored.reviewCount,7)
console.log('PASS: playlist sanitization, order boundaries, dynamic collection statistics, migration preserves playlists and existing data')
